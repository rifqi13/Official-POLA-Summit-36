   <script>
       // Fungsi untuk tombol navigasi
       function scrollGallery(id, scrollAmount) {
           const container = document.getElementById(id);
           if (container) {
               container.scrollBy({
                   left: scrollAmount,
                   behavior: 'smooth'
               });
           }
       }

       // Auto scroll setiap 5 detik (opsional)
       let autoScrollInterval;

       function startAutoScroll() {
           const container = document.getElementById('gallery-scroll');
           if (!container) return;

           autoScrollInterval = setInterval(() => {
               if (container.scrollLeft + container.clientWidth >= container.scrollWidth - 10) {
                   container.scrollTo({
                       left: 0,
                       behavior: 'smooth'
                   });
               } else {
                   container.scrollBy({
                       left: 300,
                       behavior: 'smooth'
                   });
               }
           }, 5000);
       }

       function stopAutoScroll() {
           if (autoScrollInterval) {
               clearInterval(autoScrollInterval);
           }
       }

       // Mulai auto scroll saat halaman dimuat
       document.addEventListener('DOMContentLoaded', function() {
           startAutoScroll();

           // Hentikan auto scroll saat user berinteraksi
           const container = document.getElementById('gallery-scroll');
           if (container) {
               container.addEventListener('mouseenter', stopAutoScroll);
               container.addEventListener('mouseleave', startAutoScroll);
               container.addEventListener('touchstart', stopAutoScroll);
               container.addEventListener('touchend', startAutoScroll);
           }
       });
   </script>